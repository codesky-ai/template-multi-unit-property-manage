-- ==============================================
-- التحقق من البيانات المدرجة
-- ==============================================

-- عرض ملخص البيانات المدرجة
SELECT 'المالكين' as table_name, COUNT(*) as count FROM owners
UNION ALL
SELECT 'العقارات', COUNT(*) FROM properties
UNION ALL
SELECT 'المستأجرين', COUNT(*) FROM tenants
UNION ALL
SELECT 'الوحدات', COUNT(*) FROM units
UNION ALL
SELECT 'العقود', COUNT(*) FROM contracts
UNION ALL
SELECT 'المدفوعات', COUNT(*) FROM payments
UNION ALL
SELECT 'طلبات الصيانة', COUNT(*) FROM maintenance_requests;

-- عرض بعض البيانات للتأكد من صحة الإدراج
SELECT
    p.name as property_name,
    u.unit_number,
    u.is_available,
    t.name as tenant_name
FROM properties p
LEFT JOIN units u ON p.id = u.property_id
LEFT JOIN tenants t ON u.current_tenant_id = t.id
ORDER BY p.name, u.unit_number;

-- حساب الإحصائيات الأساسية
SELECT
    COUNT(DISTINCT p.id) as total_properties,
    COUNT(u.id) as total_units,
    SUM(CASE WHEN u.is_available = FALSE THEN 1 ELSE 0 END) as occupied_units,
    SUM(CASE WHEN u.is_available = TRUE THEN 1 ELSE 0 END) as available_units,
    SUM(CASE WHEN c.status = 'نشط' THEN u.monthly_rent ELSE 0 END) as monthly_revenue
FROM properties p
LEFT JOIN units u ON p.id = u.property_id
LEFT JOIN contracts c ON u.id = c.unit_id AND c.status = 'نشط';

